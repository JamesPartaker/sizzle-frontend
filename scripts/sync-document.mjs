import { cp, mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { resolve, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "packages/document");
const require = createRequire(resolve(source, "package.json"));
const { create } = require("fontkit");
const manifest = {};
for (const file of await readdir(resolve(source, "assets"))) {
  if (!/\.(ttf|otf|png|svg)$/.test(file)) continue;
  const bytes = await readFile(resolve(source, "assets", file));
  const id = "builtin_" + basename(file).replace(/[^a-zA-Z0-9]/g, "_");
  const font = /\.(ttf|otf)$/.test(file) ? create(bytes) : null;
  const resource = {
    kind: font ? "font" : "image",
    source: {
      scope: "library",
      assetId: id,
      revisionId: "1",
      renditionId: "original",
    },
    mediaType: font
      ? "font/ttf"
      : file.endsWith(".png")
        ? "image/png"
        : "image/svg+xml",
    sha256: createHash("sha256").update(bytes).digest("hex"),
    byteLength: bytes.length,
  };
  if (file.endsWith(".png")) {
    resource.pixelWidth = bytes.readUInt32BE(16);
    resource.pixelHeight = bytes.readUInt32BE(20);
  }
  const meta = font
    ? {
        family: font.name.records.preferredFamily?.en || font.familyName,
        style: /italic|oblique/i.test(font.subfamilyName) ? "italic" : "normal",
        weight: font["OS/2"]?.usWeightClass || 400,
        axes: font.variationAxes || {},
      }
    : {};
  manifest[id] = { file, resource, ...meta };
}
let previous = {};
try {
  previous = JSON.parse(
    await readFile(resolve(source, "library.json"), "utf8"),
  );
} catch {}
for (const [id, entry] of Object.entries(previous)) {
  if (!manifest[id] || manifest[id].resource.sha256 !== entry.resource.sha256)
    throw new Error(
      `Immutable library resource ${id} changed or disappeared. Keep the old file and add a new filename for new bytes.`,
    );
}
await writeFile(
  resolve(source, "library.json"),
  JSON.stringify(manifest, null, 2) + "\n",
);
const fonts = Object.values(manifest).filter((m) => m.resource.kind === "font");
await writeFile(
  resolve(source, "fonts.css"),
  fonts
    .map(
      (f) =>
        `@font-face{font-family:${JSON.stringify(f.family)};font-style:${f.style};font-weight:${f.axes.wght ? `${f.axes.wght.min} ${f.axes.wght.max}` : f.weight};font-display:block;src:url('./assets/${f.file}') format('truetype');}`,
    )
    .join("\n") + "\n",
);
const editorRoot = resolve(root, "../sizzle-editor-ai");
await writeFile(
  resolve(editorRoot, "src/document-library.ts"),
  `// Generated by sizzle-frontend/scripts/sync-document.mjs.\nexport const library = ${JSON.stringify(manifest, null, 2)};\nexport const libraryURLs: Record<string,string> = {\n${Object.entries(
    manifest,
  )
    .map(
      ([id, m]) =>
        `${JSON.stringify(id)}: new URL(${JSON.stringify("../vendor/document/assets/" + m.file)},import.meta.url).href`,
    )
    .join(",\n")}\n};\n`,
);
for (const target of [
  resolve(root, "../sizzle-editor-ai/vendor/document"),
  resolve(root, "../sizzle-go-api/renderer/document"),
]) {
  await mkdir(target, { recursive: true });
  for (const file of [
    "README.md",
    "package.json",
    "document.schema.json",
    "library.json",
    "fonts.css",
    "src",
    "assets",
    "test",
  ])
    await cp(resolve(source, file), resolve(target, file), {
      recursive: true,
      force: true,
    });
}
const apiLibrary = resolve(root, "../sizzle-go-api/document/library");
await mkdir(apiLibrary, { recursive: true });
await cp(resolve(source, "assets"), resolve(apiLibrary, "assets"), {
  recursive: true,
  force: true,
});
await cp(resolve(source, "library.json"), resolve(apiLibrary, "library.json"));
console.log(
  `Synced @sizzle/document and ${Object.keys(manifest).length} pinned library resources to the editor and API.`,
);
